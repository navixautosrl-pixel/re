"use client";

import { useEffect } from "react";
import Lenis from "lenis";

/**
 * Global buttery-smooth scroll physics — the single change that makes the
 * whole page feel premium instead of just individually-animated. Skipped
 * entirely under prefers-reduced-motion (native scroll, no interpolation).
 */
export function SmoothScroll() {
  useEffect(() => {
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

    const lenis = new Lenis({
      duration: 1.05,
      easing: (t: number) => 1 - Math.pow(1 - t, 3),
      smoothWheel: true,
    });

    let frameId: number;
    function raf(time: number) {
      lenis.raf(time);
      frameId = requestAnimationFrame(raf);
    }
    frameId = requestAnimationFrame(raf);

    return () => {
      cancelAnimationFrame(frameId);
      lenis.destroy();
    };
  }, []);

  return null;
}
